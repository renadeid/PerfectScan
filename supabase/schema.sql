create policy "reports_files_select" on storage.objects
for select to authenticated
using (
  bucket_id = 'reports'
  and (
    public.is_admin()
    or exists (
      select 1 from public.reports r
      where r.file_path = name
        and r.patient_id = (select auth.uid())
        and r.status = 'ready'
    )
  )
);

